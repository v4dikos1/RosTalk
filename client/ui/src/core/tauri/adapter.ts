// Tauri adapter: the only module allowed to import `@tauri-apps/*` (enforced
// by the eslint `no-restricted-imports` rule). Bindings are generated by
// `make gen-ipc` from the Rust commands and events.

/** True when the page runs inside the desktop shell. */
export function hasTauriRuntime(): boolean {
  return typeof window !== "undefined" && "__TAURI_INTERNALS__" in window;
}

/**
 * The generated binding names ChatTarget variant fields in snake_case because
 * serde does not camelCase struct-variant fields. The UI keeps the camelCase
 * shape and converts at this one boundary.
 */
function toBindingTarget(target: ChatTarget) {
  return target.kind === "channel"
    ? { kind: "channel" as const, channel_id: target.channelId }
    : { kind: "dm" as const, peer_id: target.peerId };
}

/**
 * The generated binding types `fontScale` as a number because Rust stores a
 * `u16`; the core snaps it to 100/112/125 on every save, and the UI validates
 * it on hydrate, so narrowing the union here is safe.
 */
function fromBindingSettings(settings: ClientSettings_Serialize): ClientSettings {
  return settings as unknown as ClientSettings;
}

